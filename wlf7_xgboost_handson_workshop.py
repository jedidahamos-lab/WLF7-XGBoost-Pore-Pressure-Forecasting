# ------------------------------------------------------------
# Function to generate formatted SHAP summary plots
# ------------------------------------------------------------

def plot_shap_summary(
    shap_values,
    X_data,
    feature_names,
    title,
    output_file
):

    plt.figure(figsize=(13, 10))

    shap.summary_plot(
        shap_values,
        X_data,
        feature_names=feature_names,
        max_display=20,
        show=False,
        plot_size=None
    )

    # Get the main SHAP plotting axis
    ax = plt.gca()

    # Reduce horizontal-axis tick font
    ax.tick_params(
        axis="x",
        labelsize=8,
        pad=4
    )

    # Reduce the number of horizontal-axis ticks
    ax.xaxis.set_major_locator(
        MaxNLocator(nbins=5)
    )

    # Display SHAP values in scientific notation
    ax.ticklabel_format(
        axis="x",
        style="sci",
        scilimits=(0, 0),
        useMathText=True
    )

    # Horizontal-axis label
    ax.set_xlabel(
        "SHAP value (impact on model output)",
        fontsize=9,
        labelpad=8
    )

    # Vertical-axis labels
    ax.tick_params(
        axis="y",
        labelsize=9
    )

    # Title
    ax.set_title(
        title,
        fontsize=11,
        fontweight="bold",
        pad=12
    )

    # Improve layout
    plt.tight_layout()

    # Save high-resolution figure
    plt.savefig(
        output_file,
        dpi=600,
        bbox_inches="tight",
        facecolor="white"
    )

    plt.show()

    plt.close()


