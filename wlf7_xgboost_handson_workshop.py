"""## 4A. Track A — audit and reproduce the original five-minute window design

The code uses `L=48`, `H=12`, `stride=2`, then selects target indices `[0, 3, 6, 11]`. At five-minute sampling, this is a 4-hour input history and forecast targets at approximately 5, 20, 35 and 60 minutes after the input window ends.

"""

L5, H5, STRIDE5 = 48, 12, 2
X5_list, Y5_list, t5_list = [], [], []

arr5 = df5_model[FEATURES].to_numpy(dtype=float)
for t in range(L5, len(df5_model) - H5 + 1, STRIDE5):
    X5_list.append(arr5[t-L5:t, :])
    Y5_list.append(np.column_stack([
        arr5[t:t+H5, FEATURES.index("PP1")],
        arr5[t:t+H5, FEATURES.index("PP2")]
    ]))
    t5_list.append(df5_model.index[t:t+H5])

X5 = np.asarray(X5_list)
